import tkinter as tk

# Функція, яка спрацьовує при натисканні на кнопку
def button_click(): # Додано двокрапку — вона обов'язкова після оголошення функції
    # Змінюємо розмір вікна на 500х400. Значення мають бути в лапках як рядок.
    root.geometry("500x400") 

    # Змінюємо властивості напису:
    # Текст, кольори та шрифти — це рядки, тому вони мають бути в лапках.
    # Параметри розділяються комами, а значення присвоюються через "="
    label.config(
        text="Рівненський ліцей №1", 
        fg="blue",                  # Виправлено fg-blue на fg="blue"
        bg="yellow",                # Виправлено bg-yellow на bg="yellow"
        font=("Arial", 16, "bold")  # Шрифт — це кортеж (tuple), параметри через кому
    )

# Створення головного вікна
root = tk.Tk() # Виправлено tk,Tk на tk.Tk (методи викликаються через крапку)
root.title("Завдання 4.3.5") # Текст заголовка має бути в лапках

# Початкові значення вікна (розмір у форматі "ШиринаxВисота")
root.geometry("300x200") 

# Початкові значення напису
# Використовуємо "=" для присвоєння значень параметрам
label = tk.Label(root, text="Тут буде назва закладу", font=("Arial", 12))
label.pack(pady=30) # Виправлено pady-30 на pady=30

# Створення кнопки. Параметр command вказує на назву функції БЕЗ дужок.
# Виправлено tk.BUtton на tk.Button (регістр важливий)
button = tk.Button(root, text="Змінити налаштування", command=button_click)
button.pack() # Додано метод pack(), щоб кнопку було видно у вікні

# Запуск головного циклу програми
root.mainloop()
